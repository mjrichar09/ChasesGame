/**
 * Seeded random numbers for the sim.
 *
 * `sim/` never calls Math.random: a race is a pure function of its seed and
 * the inputs, which is what makes headless tests repeatable and what online
 * multiplayer will lean on later. mulberry32 — tiny, fast, good enough.
 */
export class Rng {
  private state: number;

  constructor(seed: number) {
    this.state = seed >>> 0 || 0x9e3779b9;
  }

  /** Uniform in [0, 1). */
  next(): number {
    let t = (this.state = (this.state + 0x6d2b79f5) >>> 0);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }

  range(lo: number, hi: number): number {
    return lo + (hi - lo) * this.next();
  }
}
